"use strict";


/* ========================================
   슬라이드 번호 관련 요소
======================================== */

const currentSlide =
  document.querySelector(".current-slide");

const totalSlide =
  document.querySelector(".total-slide");


/* ========================================
   전체 슬라이드 개수

   현재 총 6개
======================================== */

const slideCount = 6;


/* HTML의 전체 슬라이드 숫자 표시 */
totalSlide.textContent = slideCount;


/* ========================================
   Swiper Main Slide
======================================== */

const mainSlideSwiper =
  new Swiper(".main-slide-swiper", {

    /*
      마지막 슬라이드 다음에는
      다시 첫 번째 슬라이드로 이동
    */
    loop: true,


    /*
      한 화면에 슬라이드 1장 표시
    */
    slidesPerView: 1,

    slidesPerGroup: 1,


    /*
      슬라이드 사이 여백 없음
    */
    spaceBetween: 0,


    /*
      슬라이드 전환 애니메이션 속도
      단위 : ms
    */
    speed: 700,


    /* ========================================
       자동 슬라이드

       3000ms = 3초
    ========================================= */

    autoplay: {

      /* 3초마다 다음 슬라이드 */
      delay: 3000,

      /*
        사용자가 이전/다음 버튼을 클릭해도
        자동 재생을 중지하지 않습니다.
      */
      disableOnInteraction: false
    },


    /* ========================================
       이전 / 다음 버튼
    ========================================= */

    navigation: {

      /* 다음 버튼 */
      nextEl: ".slide-next",

      /* 이전 버튼 */
      prevEl: ".slide-prev"

    },


    /* ========================================
       Swiper Event
    ========================================= */

    on: {

      /*
        Swiper가 최초 실행될 때
        현재 슬라이드 번호 표시
      */
      init: function () {

        currentSlide.textContent =
          this.realIndex + 1;

      },


      /*
        슬라이드가 변경될 때마다
        현재 페이지 번호 변경

        realIndex 사용 이유:
        loop:true 상태에서는
        복제 슬라이드가 만들어지기 때문
      */
      slideChange: function () {

        currentSlide.textContent =
          this.realIndex + 1;

      }

    }

  });

  /* ========================================
   Product Banner Swiper
======================================== */

const productBannerSwiper =
  new Swiper(".product-banner-swiper", {

    /* ========================================
       한 화면에 상품 4개 노출
    ========================================= */
    slidesPerView: 4,


    /* ========================================
       한 번 이동할 때 4개씩 이동

       1~4번 = GROUP A
       5~8번 = GROUP B
    ========================================= */
    slidesPerGroup: 4,


    /* ========================================
       카드 사이 간격

       요청사항 : 20px
    ========================================= */
    spaceBetween: 20,


    /* ========================================
       GROUP B 다음 다시 GROUP A로 연결
    ========================================= */
    loop: true,


    /* ========================================
       슬라이드 전환 속도
    ========================================= */
    speed: 700,


    /* ========================================
       자동 슬라이드

       요청사항 :
       10초마다 다음 그룹으로 이동
    ========================================= */
    autoplay: {

      /* 10초 */
      delay: 5000,

      /*
        화살표를 클릭한 이후에도
        자동 슬라이드 계속 실행
      */
      disableOnInteraction: false,

      /*
        현재 슬라이드가 이동 중일 때는
        다음 자동 실행을 기다림
      */
      waitForTransition: true

    },


    /* ========================================
       좌 / 우 화살표
    ========================================= */
    navigation: {

      nextEl: ".product-slide-next",

      prevEl: ".product-slide-prev"

    }

  });