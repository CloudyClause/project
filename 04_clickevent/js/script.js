$(function () {

  // ========================================
  // fadeOut
  // fade-box를 부드럽게 숨김
  // ========================================
  $(".fade-out-btn").click(function () {
    $(".fade-box").fadeOut();
  });


  // ========================================
  // fadeIn
  // fade-box를 부드럽게 보여줌
  // ========================================
  $(".fade-in-btn").click(function () {
    $(".fade-box").fadeIn();
  });


  // ========================================
  // fadeToggle
  // 클릭할 때마다 부드럽게 숨김 / 표시
  // ========================================
  $(".fade-toggle-btn").click(function () {
    $(".fade-toggle-box").fadeToggle();
  });


  // ========================================
  // slideUp
  // slide-box 높이를 줄이면서 숨김
  // ========================================
  $(".slide-up-btn").click(function () {
    $(".slide-box").slideUp();
  });


  // ========================================
  // slideDown
  // slide-box를 다시 200px 높이로 표시
  // ========================================
  $(".slide-down-btn").click(function () {
    $(".slide-box").slideDown();
  });


  // ========================================
  // slideToggle
  // 클릭할 때마다 높이 0 ↔ 200px
  // ========================================
  $(".slide-toggle-btn").click(function () {
    $(".slide-toggle-box").slideToggle();
  });


  // ========================================
  // ani1
  // 현재 위치에서 오른쪽으로 500px 이동
  // ========================================
  $(".ani1-btn").click(function () {
    $(".animation-box").animate({
      left: "500px"
    });
  });


  // ========================================
  // ani2
  // 원래 위치로 이동
  // ========================================
  $(".ani2-btn").click(function () {
    $(".animation-box").animate({
      left: "0px"
    });
  });

});